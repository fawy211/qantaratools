  function localeFromPath() {
    const first = location.pathname.split('/').filter(Boolean)[0];
    return Object.prototype.hasOwnProperty.call(LOCALES, first) ? first : null;
  }

  function storedLocale() {
    try {
      const value = localStorage.getItem(STORAGE_KEY);
      return Object.prototype.hasOwnProperty.call(LOCALES, value) ? value : 'en';
    } catch (_) { return 'en'; }
  }

  const pathLocale = localeFromPath();
  const queryMatch = String(location.search || '').match(/[?&]locale=([a-z]{2})(?:&|$)/i);
  const queryLocale = queryMatch && Object.prototype.hasOwnProperty.call(LOCALES, queryMatch[1].toLowerCase())
    ? queryMatch[1].toLowerCase() : null;
  let current = pathLocale || queryLocale || storedLocale();
  if (pathLocale || queryLocale) {
    try { localStorage.setItem(STORAGE_KEY, pathLocale || queryLocale); } catch (_) {}
  }

  function applyDocumentLocale() {
    document.documentElement.lang = current;
    document.documentElement.dir = LOCALES[current].dir;
    document.documentElement.dataset.locale = current;
  }

  function setLocale(locale) {
    if (!Object.prototype.hasOwnProperty.call(LOCALES, locale)) return false;
    current = locale;
    try { localStorage.setItem(STORAGE_KEY, locale); } catch (_) {}
    applyDocumentLocale();
    if (typeof window.dispatchEvent === 'function' && typeof CustomEvent === 'function') {
      window.dispatchEvent(new CustomEvent('qt:localechange', { detail: { locale } }));
    }
    return true;
  }

  function t(key, fallback) {
    return (MESSAGES[current] && MESSAGES[current][key]) ||
      (EXTRA_MESSAGES[current] && EXTRA_MESSAGES[current][key]) ||
      (CURRENCY_MESSAGES[current] && CURRENCY_MESSAGES[current][key]) ||
      (IMAGE_MESSAGES[current] && IMAGE_MESSAGES[current][key]) ||
      (PDF_MESSAGES[current] && PDF_MESSAGES[current][key]) ||
      (TEXT_TOOL_MESSAGES[current] && TEXT_TOOL_MESSAGES[current][key]) ||
      (BUSINESS_MESSAGES[current] && BUSINESS_MESSAGES[current][key]) ||
      (MORE_TEXT_MESSAGES[current] && MORE_TEXT_MESSAGES[current][key]) ||
      (MEDIA_MESSAGES[current] && MEDIA_MESSAGES[current][key]) ||
      (CORE_MESSAGES[current] && CORE_MESSAGES[current][key]) ||
      (EXTRA_CORE_MESSAGES[current] && EXTRA_CORE_MESSAGES[current][key]) ||
      (DEV_TOOL_MESSAGES[current] && DEV_TOOL_MESSAGES[current][key]) ||
      (DEV_EXTRA_MESSAGES[current] && DEV_EXTRA_MESSAGES[current][key]) ||
      (FINAL_TOOL_MESSAGES[current] && FINAL_TOOL_MESSAGES[current][key]) ||
      (FANCY_MESSAGES[current] && FANCY_MESSAGES[current][key]) ||
      (HOME_MESSAGES[current] && HOME_MESSAGES[current][key]) ||
      MESSAGES.en[key] || EXTRA_MESSAGES.en[key] || CURRENCY_MESSAGES.en[key] || IMAGE_MESSAGES.en[key] || PDF_MESSAGES.en[key] || TEXT_TOOL_MESSAGES.en[key] || BUSINESS_MESSAGES.en[key] || MORE_TEXT_MESSAGES.en[key] || MEDIA_MESSAGES.en[key] || CORE_MESSAGES.en[key] || EXTRA_CORE_MESSAGES.en[key] || DEV_TOOL_MESSAGES.en[key] || DEV_EXTRA_MESSAGES.en[key] || FINAL_TOOL_MESSAGES.en[key] || FANCY_MESSAGES.en[key] || HOME_MESSAGES.en[key] || fallback || key;
  }

  const MESSAGE_TABLES = [MESSAGES, EXTRA_MESSAGES, CURRENCY_MESSAGES, IMAGE_MESSAGES, PDF_MESSAGES, TEXT_TOOL_MESSAGES, BUSINESS_MESSAGES, MORE_TEXT_MESSAGES, MEDIA_MESSAGES, CORE_MESSAGES, EXTRA_CORE_MESSAGES, DEV_TOOL_MESSAGES, DEV_EXTRA_MESSAGES, FINAL_TOOL_MESSAGES, FANCY_MESSAGES, HOME_MESSAGES];

  function hasTranslation(locale, key) {
    return MESSAGE_TABLES.some(table => Object.prototype.hasOwnProperty.call(table[locale] || {}, key));
  }

  function formatNumber(value, options) {
    return new Intl.NumberFormat(LOCALES[current].intl, options).format(value);
  }

  function formatDate(value, options) {
    return new Intl.DateTimeFormat(LOCALES[current].intl, options).format(value instanceof Date ? value : new Date(value));
  }

  function formatCurrency(value, currency, options) {
    return new Intl.NumberFormat(LOCALES[current].intl, {
      style: 'currency', currency: currency || 'USD', ...options
    }).format(value);
  }

  applyDocumentLocale();

  window.QTI18n = Object.freeze({
    locales: LOCALES,
    get locale() { return current; },
    get direction() { return LOCALES[current].dir; },
    t, setLocale, formatNumber, formatDate, formatCurrency, hasTranslation,
    toolTitle: (id, fallback) => t(TOOL_META[id]?.[0], fallback || id),
    toolDescription: (id, fallback) => t(TOOL_META[id]?.[1], fallback || '')
  });
